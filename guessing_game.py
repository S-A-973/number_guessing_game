
import random

def get_user_input(prompt):
    """_summary_
    This is a function to get a users input

    Args:
        prompt (int): Takes in a users guess, confirms range(0-10), and handles Value Error

    Returns:
        int : (An integer of the users guess)
    """
    while True:
        try:
            user_guess = int(input(prompt))
            if 0 < user_guess <= 10:
                return user_guess
            else:
                print("please enter an integer between 1 and 10")
        except ValueError:
            print("Please enter an integer")

def get_random_number():
    """_summary_: Uses the random module, specifically the randint() function to generate random numbers between 1-10

    Returns:
        int: _description_: This is the random number generated by the computer
    """
    number = random.randint(1, 10)
    return number

def game_score(x, y):
    """_summary_: A function that finds the diffrence between the users guess and the computer generated random number. The difference is then used to return a score.

    Args:
        x (int): _description_: Refers to the users guess
        y (int): _description_: Refers t random number generated by the computer

    Returns:
        int:score based on the diffrence, between user input and computer generated random number
    """
    difference = abs(x - y)
    
    if difference == 0:
        return 10
    elif difference <= 2:
        return 8
    elif difference <= 4:
        return 6
    elif difference <= 6:
        return 4
    elif difference <= 8:
        return 2
    else:
        return 0

    
def main():  
    """
     Runs the main game loop for a 5-round number guessing game.

    This function coordinates the game flow by picking a random number, 
    prompting the user for their guess, calculating the points earned 
    for the round, and maintaining a running total score. It prints 
    the results and remaining rounds after each turn.

    Args:
        None

    Returns:
        None (The function executes the game loop and prints results 
              directly to the standard output console).
    """ 
    
    total_score = 0
    rounds = 5
    while rounds > 0:
        user_guess = get_user_input("Guess a number: ")
        random_number = get_random_number()
        round_score = game_score(user_guess, random_number)
        total_score += round_score
        rounds -= 1
        print(f"Number of rounds remaining {rounds}. \nTotal score: {total_score}. \nNumber generted by computer is: {random_number}. \nYour guess was {user_guess}, you scored {round_score} points in this round.")

main()
    


    



